#!/usr/bin/env node
/**
 * Generates LocalAddressFixturesTest.kt from scripts/fixtures/local-address-cases.json,
 * so the background worker's Kotlin copy of the plain-HTTP rule (LocalAddress.kt)
 * is held to the same cases as src/lib/local-address.js (#194).
 * scripts/local-address.test.js fails when the committed file differs from what
 * this produces.
 *
 *   node scripts/gen-local-address-kotlin-test.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FIXTURES = new URL('./fixtures/local-address-cases.json', import.meta.url);
export const OUT = new URL('../android/app/src/test/java/com/nutritrace/app/LocalAddressFixturesTest.kt', import.meta.url);

// A Kotlin string literal: JSON escapes, plus $ (string templates).
export const kstr = (s) => JSON.stringify(s).replace(/\$/g, '\\$');

export function render() {
  const { cases } = JSON.parse(readFileSync(FIXTURES, 'utf8'));
  // (url, the answer Kotlin must give, the host it must read or null)
  const rows = cases.map(c => `        Triple(${kstr(c.url)}, ${kstr(c.kotlin || c.expect)}, ${c.kotlin || c.host === null ? 'null' : kstr(c.host)}),`).join('\n');
  return `// GENERATED by scripts/gen-local-address-kotlin-test.mjs from scripts/fixtures/local-address-cases.json.
// Do not edit by hand: change the fixtures, then run
//   node scripts/gen-local-address-kotlin-test.mjs
// The JS side runs the same cases in scripts/local-address.test.js (#194).
package com.nutritrace.app

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class LocalAddressFixturesTest {
    private val cases = listOf(
${rows}
    )

    @Test
    fun everyCaseMatchesTheJsRule() {
        val wrong = cases.filter { (url, expect, _) -> LocalAddress.classify(url) != expect }
            .map { (url, expect, _) -> "\${url} expected \${expect}, got \${LocalAddress.classify(url)}" }
        assertEquals("cases where Kotlin disagrees with the fixtures", emptyList<String>(), wrong)
    }

    @Test
    fun everyHostIsReadAsTheWebViewReadsIt() {
        val wrong = cases.filter { (_, _, host) -> host != null }
            .filter { (url, _, host) -> LocalAddress.parse(url)?.host != host }
            .map { (url, _, host) -> "\${url} expected host \${host}, got \${LocalAddress.parse(url)?.host}" }
        assertEquals("hosts Kotlin reads differently from the WebView", emptyList<String>(), wrong)
    }

    @Test
    fun workerSendsOverPlainHttpOnlyToAConfirmedLocalServer() {
        // https: the saved address, as before.
        assertEquals("https://nt.example.com/sub/", LocalAddress.workerBase("https://nt.example.com/sub/", ""))
        // Local http, confirmed: the app writes the confirmation as the WebView's
        // URL parser writes the address (canonicalServerBase), and the worker
        // sends only when its own rebuilt address is exactly that.
        assertEquals("http://192.168.1.20:3001", LocalAddress.workerBase("http://192.168.1.20:3001", "http://192.168.1.20:3001"))
        assertEquals("http://nas.local:3001/nutritrace", LocalAddress.workerBase("http://NAS.local:3001/nutritrace/", "http://nas.local:3001/nutritrace"))
        assertEquals("http://192.168.1.1", LocalAddress.workerBase("http://0xC0A80101:80", "http://192.168.1.1"))
        assertEquals("http://192.168.1.5/@evil.com", LocalAddress.workerBase("http://192.168.1.5\\\\@evil.com", "http://192.168.1.5/@evil.com"))
        // Local http not confirmed (an update from a build that allowed it), or confirmed for another address.
        assertNull(LocalAddress.workerBase("http://192.168.1.20:3001", null))
        assertNull(LocalAddress.workerBase("http://192.168.1.20:3001", ""))
        assertNull(LocalAddress.workerBase("http://192.168.1.20:3001", "http://192.168.1.21:3001"))
        assertNull(LocalAddress.workerBase("http://192.168.1.20:3001", "http://192.168.1.20:3001/other"))
        // An international host: Java and the WebView may read it as different hosts, so never.
        assertNull(LocalAddress.workerBase("http://stra\u00dfe.local:3001", "http://xn--strae-oqa.local:3001"))
        assertNull(LocalAddress.workerBase("http://stra\u00dfe.local:3001", "http://strasse.local:3001"))
        // Public http, even if something wrote it as confirmed.
        assertNull(LocalAddress.workerBase("http://203.0.113.10:3001", "http://203.0.113.10:3001"))
        assertNull(LocalAddress.workerBase("http://192.168.1.5@example.com", "http://example.com"))
        // Nothing saved, or not an http(s) URL.
        assertNull(LocalAddress.workerBase(null, null))
        assertNull(LocalAddress.workerBase("", ""))
        assertNull(LocalAddress.workerBase("ftp://192.168.1.5", "ftp://192.168.1.5"))
    }
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(new URL('.', OUT), { recursive: true });
  writeFileSync(OUT, render());
  console.log('wrote', fileURLToPath(OUT));
}
