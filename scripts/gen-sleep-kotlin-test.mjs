#!/usr/bin/env node
/**
 * Generates SleepDerivationFixturesTest.kt from scripts/fixtures/sleep-sessions.json
 * and HrvDerivationFixturesTest.kt from scripts/fixtures/hrv-nights.json, so
 * the background worker's Kotlin sleep and HRV code is held to the same cases
 * as the foreground JS (#236, #279). scripts/sleep-kotlin-parity.test.js fails
 * when a committed file differs from what this produces.
 *
 *   node scripts/gen-sleep-kotlin-test.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const FIXTURES = new URL('./fixtures/sleep-sessions.json', import.meta.url);
export const OUT = new URL('../android/app/src/test/java/com/nutritrace/app/SleepDerivationFixturesTest.kt', import.meta.url);
const HRV_FIXTURES = new URL('./fixtures/hrv-nights.json', import.meta.url);
export const OUT_HRV = new URL('../android/app/src/test/java/com/nutritrace/app/HrvDerivationFixturesTest.kt', import.meta.url);

// AndroidX SleepSessionRecord.STAGE_TYPE_* values.
const STAGE = { UNKNOWN: 0, AWAKE: 1, SLEEPING: 2, OUT_OF_BED: 3, LIGHT: 4, DEEP: 5, REM: 6, AWAKE_IN_BED: 7 };

const kstr = (s) => JSON.stringify(s).replace(/\$/g, '\\$');
const ms = (iso) => {
  const v = Date.parse(iso);
  if (!Number.isFinite(v)) throw new Error(`bad timestamp in fixtures: ${iso}`);
  return `${v}L`;
};

function session(s) {
  const stages = s.stages.map(([name, a, b]) => {
    if (!(name in STAGE)) throw new Error(`unknown stage in fixtures: ${name}`);
    return `st(${STAGE[name]}, ${ms(a)}, ${ms(b)})`;
  });
  const args = [kstr(s.id), kstr(s.origin), ms(s.start), ms(s.end), ...stages];
  return `s(${args.join(', ')})`;
}

function expected(expect) {
  const entries = Object.entries(expect);
  if (!entries.length) return 'emptyMap<String, Number>()';
  return `mapOf<String, Number>(${entries.map(([k, v]) => `${kstr(k)} to ${v}`).join(', ')})`;
}

export function render() {
  const { cases } = JSON.parse(readFileSync(FIXTURES, 'utf8'));
  const tests = cases.map((c, i) => {
    const n = String(i + 1).padStart(2, '0');
    const slug = c.name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 60);
    const sessions = c.sessions.map(session);
    const list = sessions.length ? `listOf(\n            ${sessions.join(',\n            ')}\n        )` : 'emptyList<SleepDerivation.RawSession>()';
    const reversed = sessions.length > 1
      ? `\n        assertEquals(${kstr(c.name + ' (records in reverse order)')}, expected, derive(sessions.reversed()))`
      : '';
    return `    @Test
    fun case${n}_${slug}() {
        val sessions = ${list}
        val derive = { list: List<SleepDerivation.RawSession> -> SleepDerivation.derive(list, ${kstr(c.date)}, ZoneId.of(${kstr(c.zone)})) }
        val expected = ${expected(c.expect)}
        assertEquals(${kstr(c.name)}, expected, derive(sessions))${reversed}
    }
`;
  });

  return `// GENERATED by scripts/gen-sleep-kotlin-test.mjs from scripts/fixtures/sleep-sessions.json.
// Do not edit by hand: change the fixtures, then run
//   node scripts/gen-sleep-kotlin-test.mjs
// The JS side runs the same cases in scripts/sleep-sessions.test.js (#236).
package com.nutritrace.app

import androidx.health.connect.client.records.SleepSessionRecord
import org.junit.Assert.assertEquals
import org.junit.Test
import java.time.ZoneId

class SleepDerivationFixturesTest {
    private fun s(id: String, origin: String, start: Long, end: Long, vararg stages: SleepDerivation.RawStage) =
        SleepDerivation.RawSession(id, origin, start, end, stages.toList())

    private fun st(stage: Int, start: Long, end: Long) = SleepDerivation.RawStage(stage, start, end)

    @Test
    fun stageConstantsAreAndroidX() {
        assertEquals(SleepSessionRecord.STAGE_TYPE_UNKNOWN, SleepDerivation.STAGE_UNKNOWN)
        assertEquals(SleepSessionRecord.STAGE_TYPE_AWAKE, SleepDerivation.STAGE_AWAKE)
        assertEquals(SleepSessionRecord.STAGE_TYPE_SLEEPING, SleepDerivation.STAGE_SLEEPING)
        assertEquals(SleepSessionRecord.STAGE_TYPE_OUT_OF_BED, SleepDerivation.STAGE_OUT_OF_BED)
        assertEquals(SleepSessionRecord.STAGE_TYPE_LIGHT, SleepDerivation.STAGE_LIGHT)
        assertEquals(SleepSessionRecord.STAGE_TYPE_DEEP, SleepDerivation.STAGE_DEEP)
        assertEquals(SleepSessionRecord.STAGE_TYPE_REM, SleepDerivation.STAGE_REM)
        assertEquals(SleepSessionRecord.STAGE_TYPE_AWAKE_IN_BED, SleepDerivation.STAGE_AWAKE_IN_BED)
    }

${tests.join('\n')}}
`;
}

/** A Kotlin Double literal: 45 -> 45.0, 41.3 -> 41.3. */
const kdouble = (v) => {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error(`bad number in fixtures: ${v}`);
  return Number.isInteger(v) ? `${v}.0` : String(v);
};

export function renderHrv() {
  const { cases } = JSON.parse(readFileSync(HRV_FIXTURES, 'utf8'));
  const tests = cases.map((c, i) => {
    const n = String(i + 1).padStart(2, '0');
    const slug = c.name.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 60);
    const sessions = c.sessions.map(session);
    const list = sessions.length ? `listOf(\n            ${sessions.join(',\n            ')}\n        )` : 'emptyList<SleepDerivation.RawSession>()';
    const samples = c.samples.map(([t, v]) => `h(${ms(t)}, ${kdouble(v)})`);
    const sampleList = samples.length ? `listOf(${samples.join(', ')})` : 'emptyList<SleepDerivation.HrvSample>()';
    const entries = Object.entries(c.expect);
    const expected = entries.length
      ? `mapOf<String, Number>(${entries.map(([k, v]) => `${kstr(k)} to ${kdouble(v)}`).join(', ')})`
      : 'emptyMap<String, Number>()';
    const reversed = samples.length > 1 || sessions.length > 1
      ? `\n        assertEquals(${kstr(c.name + ' (records in reverse order)')}, expected, derive(sessions.reversed(), samples.reversed()))`
      : '';
    return `    @Test
    fun case${n}_${slug}() {
        val sessions = ${list}
        val samples = ${sampleList}
        val derive = { ss: List<SleepDerivation.RawSession>, hs: List<SleepDerivation.HrvSample> -> SleepDerivation.deriveHrv(ss, hs, ${kstr(c.date)}, ZoneId.of(${kstr(c.zone)})) }
        val expected = ${expected}
        assertEquals(${kstr(c.name)}, expected, derive(sessions, samples))${reversed}
    }
`;
  });

  return `// GENERATED by scripts/gen-sleep-kotlin-test.mjs from scripts/fixtures/hrv-nights.json.
// Do not edit by hand: change the fixtures, then run
//   node scripts/gen-sleep-kotlin-test.mjs
// The JS side runs the same cases in scripts/hrv-nights.test.js (#279).
package com.nutritrace.app

import org.junit.Assert.assertEquals
import org.junit.Test
import java.time.ZoneId

class HrvDerivationFixturesTest {
    private fun s(id: String, origin: String, start: Long, end: Long, vararg stages: SleepDerivation.RawStage) =
        SleepDerivation.RawSession(id, origin, start, end, stages.toList())

    private fun st(stage: Int, start: Long, end: Long) = SleepDerivation.RawStage(stage, start, end)

    private fun h(time: Long, rmssd: Double) = SleepDerivation.HrvSample(time, rmssd)

${tests.join('\n')}}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(new URL('.', OUT), { recursive: true });
  writeFileSync(OUT, render());
  console.log('wrote', fileURLToPath(OUT));
  writeFileSync(OUT_HRV, renderHrv());
  console.log('wrote', fileURLToPath(OUT_HRV));
}
